export const OUTPUT_LANG: Record<Locale, string> = {
  ja: "Japanese",
  en: "English",
  zh: "Simplified Chinese",
  es: "Spanish",
  fr: "French",
  de: "German",
  pt: "Portuguese",
  it: "Italian",
  ru: "Russian",
  ar: "Arabic",
  ko: "Korean",
  hi: "Hindi",
  id: "Indonesian",
  tr: "Turkish",
};

export function outputLang(locale: Locale) {
  return OUTPUT_LANG[locale] ?? "Japanese";
}

export function isLocale(v: unknown): v is Locale {
  return typeof v === "string" && (LOCALES as readonly string[]).includes(v);
}

export function detectLocale(): Locale {
  if (typeof navigator === "undefined") return "ja";
  const list = [...(navigator.languages ?? []), navigator.language].filter(Boolean);
  for (const raw of list) {
    const low = raw.toLowerCase();
    if (low.startsWith("zh")) return "zh";
    const base = low.slice(0, 2);
    if (isLocale(base)) return base;
  }
  return "en";
}

export function formatMsg(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));
}

export function t(locale: Locale, key: MsgKey, vars?: Record<string, string | number>) {
  const table = TABLES[locale] ?? TABLES.en;
  return formatMsg(table[key] || TABLES.en[key] || key, vars);
}
